"""
OmniBioAI alembic.env.

Purpose:
    Defines run_migrations_offline and run_migrations_online for alembic.env.

Author:
    Manish Kumar <manish@omnibioai.org>
"""

from logging.config import fileConfig
import os

from alembic import context
from sqlalchemy import engine_from_config, pool

# Ensure app/ is importable when alembic is invoked from the repo root
# (alembic.ini sets prepend_sys_path = . for this).
from app.db.base import Base

# Imported for its side effect of registering every ORM model class onto
# Base.metadata, so target_metadata below is complete. As of this revision
# no models exist yet for the new multi-tenant tables (0001/0002 are
# hand-written, not autogenerated) -- this import matters for whichever
# future revision starts using --autogenerate.
import app.db.models  # noqa: F401,E402

# this is the Alembic Config object, which provides access to values within
# the .ini file in use.
config = context.config

# Programmatic callers (the isolated migration tests) may set sqlalchemy.url
# directly. CLI execution must use a separately provisioned migration URL;
# never fall back to the runtime DML principal.
if not config.get_main_option("sqlalchemy.url"):
    migration_database_url = os.getenv("MIGRATION_DATABASE_URL", "").strip()
    if not migration_database_url:
        raise RuntimeError(
            "MIGRATION_DATABASE_URL is required for Alembic CLI execution; "
            "refusing to use the Auth runtime database principal."
        )
    config.set_main_option("sqlalchemy.url", migration_database_url)

# Interpret the config file for Python logging. disable_existing_loggers
# defaults to True, which silently disables (permanently, for the rest of
# the process -- not just during this call) every logger not explicitly
# listed in alembic.ini's [loggers] section, including every application
# logger the app itself creates (e.g. permission_parity.py's). Explicit
# False here to avoid that footgun -- discovered when running the test
# suite: tests/test_migrations.py invoking Alembic commands was silently
# disabling tests/test_permission_parity.py's caplog-based assertions
# whenever it ran first in the same session.
if config.config_file_name is not None:
    fileConfig(config.config_file_name, disable_existing_loggers=False)

target_metadata = Base.metadata


def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode.

    Emits SQL to stdout instead of executing against a live connection --
    useful for `alembic upgrade head --sql` review before applying anything
    for real (see docs/MIGRATIONS.md verification steps).
    """
    url = config.get_main_option("sqlalchemy.url")
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )

    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run migrations in 'online' mode, against a live connection."""
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:
        context.configure(connection=connection, target_metadata=target_metadata)

        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
